    CUDAStorage::CUDAStorage(size_t numbytes) {        		
		ptr = CachingAllocator::instance().allocate(numbytes);
        m_numbytes = numbytes;
    }

    CUDAStorage::~CUDAStorage() {        		
		CachingAllocator::instance().deallocate(ptr);
    }
