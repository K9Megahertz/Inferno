#include "cudaops.h"

namespace Inferno {

    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Function sum_kernel
    //
    //
    //
    //
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    template<typename AT>
    __global__ void sum_kernel(const AT* aptr, AT* optr, size_t N) {        

        size_t i = blockIdx.x * blockDim.x + threadIdx.x;

        if (i >= N) {
            return;
        }

        atomicAdd(optr, aptr[i]);
    }


    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Function cuda_sum
    //
    //
    //
    //
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    template<typename AT>
    void cuda_sum(const AT* aptr, AT* outptr, size_t N) {
        dim3 block(256);
        dim3 grid((N + block.x - 1) / block.x);
        sum_kernel << <grid, block >> > (aptr, outptr, N);
    }


    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Explicit instantiations
    //
    //
    //
    //
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    template void cuda_sum<int>(const int*, int*, size_t);
    template void cuda_sum<float>(const float*, float*, size_t);
    template void cuda_sum<double>(const double*, double*, size_t);

    

}